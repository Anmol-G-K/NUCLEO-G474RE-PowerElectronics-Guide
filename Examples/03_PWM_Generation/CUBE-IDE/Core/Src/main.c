/* Convert a percentage (integer, 0-100) and a timer period count to a CCR
   tick value. Both arguments must be compile-time constants — the compiler
   folds the entire expression to a single immediate with zero runtime cost.
   Example: DUTY_TO_TICKS(75, 34000) -> (75 * 34000) / 100 -> 25500         */
#define DUTY_TO_TICKS(pct, period)  (((uint32_t)(pct) * (uint32_t)(period)) / 100U)

/* TIM1 - 5 kHz PWM on CH1  (ARR = 33999, period counts = 34000) */
#define TIM1_ARR            34000U
#define TIM1_DUTY_75        DUTY_TO_TICKS(75, TIM1_ARR)   /* 25500 */
#define TIM1_DUTY_25        DUTY_TO_TICKS(25, TIM1_ARR)   /* 8500  */

/* TIM8 - 20 kHz PWM on CH1 and CH1N (ARR = 8499, period counts = 8500)
   CH1  -> 65% duty (active high)
   CH1N -> 35% duty (logical complement of CH1, OCNPolarity HIGH)          */
#define TIM8_ARR            8500U
#define TIM8_DUTY_65        DUTY_TO_TICKS(65, TIM8_ARR)   /* 5525  */

/* HRTIM Timer A - pulse sweep 15% -> 95% -> 15% (triangular)
   Period register = 0xFFDF = 65503, counts = 65504
   Preload enabled + UpdateTrigger = Timer A period event (set via IOC):
   CMP1 writes go to shadow register and transfer to active at period
   boundary — guarantees glitch-free pulse edges during the sweep.           */
#define HRTIM_ARR           65504U
#define HRTIM_CMP_MIN       DUTY_TO_TICKS(15, HRTIM_ARR)  /* 9825  */
