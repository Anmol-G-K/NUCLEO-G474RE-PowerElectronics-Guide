#define HRTIM_SWEEP_STEPS   80U
#define HRTIM_SWEEP_STEP_SZ ((HRTIM_CMP_MAX - HRTIM_CMP_MIN) / HRTIM_SWEEP_STEPS)
#define HRTIM_SWEEP_MS      50U    /* update interval: 0.05 s */

